// Copy-to-clipboard — label swap only, no toast (silent success is the feedback).
function wireCopyButtons(scope) {
  (scope || document).querySelectorAll(".copy-btn").forEach((btn) => {
    if (btn.dataset.wired) return;
    btn.dataset.wired = "true";
    btn.addEventListener("click", async () => {
      const value = btn.dataset.copy || "";
      try {
        await navigator.clipboard.writeText(value);
      } catch {
        // Clipboard API unavailable (insecure context, permissions) — fall back silently;
        // the command is already visible in the block for manual copy.
        return;
      }
      btn.dataset.state = "copied";
      btn.setAttribute("aria-label", "Copied");
      setTimeout(() => {
        delete btn.dataset.state;
        btn.setAttribute("aria-label", "Copy to clipboard");
      }, 2500);
    });
  });
}

// Install channel tabs — roving tabindex, arrow-key navigation.
function wireTabs() {
  const tabs = Array.from(document.querySelectorAll('[role="tab"]'));
  if (!tabs.length) return;

  function select(tab, focus) {
    tabs.forEach((t) => {
      const active = t === tab;
      t.setAttribute("aria-selected", String(active));
      t.tabIndex = active ? 0 : -1;
      const panel = document.getElementById(t.getAttribute("aria-controls"));
      if (panel) {
        panel.classList.toggle("is-active", active);
        if (active) panel.removeAttribute("hidden");
        else panel.setAttribute("hidden", "");
      }
    });
    if (focus) tab.focus();
  }

  tabs.forEach((tab, i) => {
    tab.addEventListener("click", () => select(tab, false));
    tab.addEventListener("keydown", (e) => {
      let next = null;
      if (e.key === "ArrowRight") next = tabs[(i + 1) % tabs.length];
      else if (e.key === "ArrowLeft") next = tabs[(i - 1 + tabs.length) % tabs.length];
      else if (e.key === "Home") next = tabs[0];
      else if (e.key === "End") next = tabs[tabs.length - 1];
      if (next) {
        e.preventDefault();
        select(next, true);
      }
    });
  });
}

// Scroll-triggered reveals — IntersectionObserver adds .is-visible once.
function wireReveals() {
  const els = document.querySelectorAll(".reveal-scroll");
  if (!els.length) return;
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    els.forEach((el) => el.classList.add("is-visible"));
    return;
  }
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          io.unobserve(entry.target);
        }
      });
    },
    { rootMargin: "0px 0px -8% 0px", threshold: 0.12 }
  );
  els.forEach((el) => io.observe(el));
}

// Animated counters — count up when the stat scrolls into view.
function wireCounters() {
  const nums = document.querySelectorAll(".count[data-count]");
  if (!nums.length) return;
  const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const run = (el) => {
    const target = parseInt(el.dataset.count, 10) || 0;
    if (reduced) {
      el.textContent = String(target);
      return;
    }
    const dur = 1100;
    const start = performance.now();
    function frame(now) {
      const p = Math.min((now - start) / dur, 1);
      const eased = 1 - Math.pow(1 - p, 3); // ease-out cubic
      el.textContent = String(Math.round(target * eased));
      if (p < 1) requestAnimationFrame(frame);
      else el.textContent = String(target);
    }
    requestAnimationFrame(frame);
  };
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          run(entry.target);
          io.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.6 }
  );
  nums.forEach((el) => io.observe(el));
}

// Skill catalog — renders assets/skills.json (generated by
// site/scripts/build-catalog.py; committed because Pages has no build step),
// with text search + native/router facets.
function wireCatalog() {
  const grid = document.getElementById("skills-grid");
  const empty = document.getElementById("skills-empty");
  const count = document.getElementById("skills-count");
  const search = document.getElementById("skill-search");
  const facets = Array.from(document.querySelectorAll(".facet"));
  if (!grid) return;

  let skills = [];
  let facet = "all";
  let query = "";

  const facetLabel = { all: "All", native: "Native", router: "Router" };
  function updateFacetLabels() {
    const n = skills.filter((s) => s.kind === "native").length;
    const r = skills.filter((s) => s.kind === "router").length;
    facets.forEach((f) => {
      const k = f.dataset.facet;
      const c = k === "native" ? n : k === "router" ? r : skills.length;
      f.textContent = `${facetLabel[k]} ${c}`;
    });
  }

  function esc(s) {
    return String(s)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  function render() {
    const q = query.trim().toLowerCase();
    const list = skills.filter((s) => {
      if (facet !== "all" && s.kind !== facet) return false;
      if (!q) return true;
      return (
        s.name.toLowerCase().includes(q) ||
        s.description.toLowerCase().includes(q)
      );
    });

    grid.innerHTML = list
      .map(
        (s) => `
      <article class="product">
        <div class="product__top">
          <h3 class="product__name">${esc(s.name)}</h3>
          <span class="product__kind">${s.kind === "router" ? "router" : "native"}</span>
        </div>
        <p class="product__desc">${esc(s.description)}</p>
        <p class="product__version">v${esc(s.version)}</p>
      </article>`
      )
      .join("");

    empty.classList.toggle("is-visible", list.length === 0);
    count.textContent = `Showing ${list.length} of ${skills.length} skills`;
  }

  fetch("assets/skills.json", { cache: "no-store" })
    .then((res) => {
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return res.json();
    })
    .then((data) => {
      skills = Array.isArray(data.skills) ? data.skills : [];
      updateFacetLabels();
      render();
    })
    .catch(() => {
      grid.innerHTML = "";
      count.textContent = "";
      const err = document.createElement("p");
      err.className = "catalog__empty is-visible";
      err.textContent = "Couldn't load assets/skills.json — browse skills/ in the repo instead.";
      grid.appendChild(err);
    });

  if (search) {
    search.addEventListener("input", () => {
      query = search.value;
      render();
    });
  }
  facets.forEach((f) => {
    f.addEventListener("click", () => {
      facet = f.dataset.facet;
      facets.forEach((x) => x.setAttribute("aria-pressed", String(x === f)));
      render();
    });
  });
}

